test("Xendit uses test credentials outside production and live credentials in production", (t) => {
  const names = [
    "NODE_ENV",
    "XENDIT_TEST_SECRET_KEY",
    "XENDIT_SECRET_KEY",
    "XENDIT_WEBHOOK_TOKEN",
    "APP_URL",
  ];
  const originalValues = new Map(
    names.map((name) => [name, process.env[name]])
  );
  t.after(() => {
    for (const [name, value] of originalValues) {
      if (value === undefined) delete process.env[name];
      else process.env[name] = value;
    }
  });

  process.env.NODE_ENV = "development";
  process.env.XENDIT_TEST_SECRET_KEY = "test-key";
  process.env.XENDIT_SECRET_KEY = "live-key";
  process.env.XENDIT_WEBHOOK_TOKEN = "callback-token";
  process.env.APP_URL = "http://localhost:3112";
  assert.deepEqual(getXenditConfig(), {
    secretKey: "test-key",
    callbackToken: "callback-token",
    appUrl: "http://localhost:3112",
    mode: "test",
  });
  assert.equal(getXenditConfig("http://localhost:3112/api/orders/1").appUrl, "http://localhost:3112");
  assert.equal(getXenditConfig("https://localhost:3112/api/orders/1").appUrl, "https://localhost:3112");
  const localAddress = Object.values(networkInterfaces()).flatMap((entries) => entries ?? [])
    .find((entry) => entry.family === "IPv4" && /^(10\.|192\.168\.|172\.(1[6-9]|2\d|3[01])\.)/.test(entry.address));
  if (localAddress) {
    assert.equal(
      getXenditConfig(`http://${localAddress.address}:3112/api/orders/1`).appUrl,
      `http://${localAddress.address}:3112`
    );
  }
  assert.throws(() => getXenditConfig("http://192.168.255.254:3112"), /current Wi-Fi address/);
  assert.throws(() => getXenditConfig("http://localhost:9999"), /current Wi-Fi address/);
  process.env.APP_URL = "http://192.168.8.100:3112";
  assert.equal(getXenditConfig().appUrl, "http://192.168.8.100:3112");
  process.env.APP_URL = "http://8.8.8.8:3112";
  assert.throws(() => getXenditConfig(), /HTTPS origin/);

  process.env.NODE_ENV = "production";
  process.env.APP_URL = "http://192.168.8.100:3112";
  assert.throws(() => getXenditConfig(), /HTTPS origin/);
  process.env.APP_URL = "https://cafe.example";
  assert.deepEqual(getXenditConfig(), {
    secretKey: "live-key",
    callbackToken: "callback-token",
    appUrl: "https://cafe.example",
    mode: "live",
  });
  assert.equal(getXenditConfig("http://localhost:3112").appUrl, "https://cafe.example");
});
