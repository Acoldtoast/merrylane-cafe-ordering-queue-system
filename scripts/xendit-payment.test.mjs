function captureEvent(overrides = {}) {
  return {
    event: "payment.capture",
    data: {
      payment_id: "py-test-123",
      payment_request_id: "pr-test-123",
      reference_id: "ml_test",
      type: "PAY",
      country: "PH",
      currency: "PHP",
      request_amount: 100,
      channel_code: "GCASH",
      status: "SUCCEEDED",
      captures: [{ capture_id: "cap-test-123", capture_amount: 100 }],
      ...overrides,
    },
  };
}

async function createDatabase(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "merrylane-xendit-"));
  const database = PGliteDatabase.open(path.join(root, "pgdata"));
  globalThis.__merrylaneDb = database;
  await database.exec(`
    CREATE TABLE orders (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      table_number INTEGER NOT NULL DEFAULT 1,
      status TEXT NOT NULL,
      payment_method TEXT NOT NULL,
      payment_status TEXT NOT NULL,
      total NUMERIC(12, 2) NOT NULL,
      payment_amount NUMERIC(12, 2),
      payment_reference TEXT,
      payment_proof_url TEXT,
      queue_number INTEGER,
      confirmed_at TEXT,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
      updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    );
    CREATE TABLE order_balance_payments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      order_id INTEGER NOT NULL,
      amount NUMERIC(12, 2) NOT NULL,
      payment_method TEXT NOT NULL,
      status TEXT NOT NULL,
      payment_reference TEXT,
      payment_proof_url TEXT,
      verified_at TEXT,
      received_by INTEGER,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    );
  `);
  t.after(async () => {
    globalThis.__merrylaneDb = undefined;
    await database.close();
    await fs.rm(root, { recursive: true, force: true });
  });
  return database;
}

test("webhook authentication requires the exact configured callback token", () => {
  assert.equal(verifyXenditCallbackToken("secret", "secret"), true);
  assert.equal(verifyXenditCallbackToken("wrong", "secret"), false);
  assert.equal(verifyXenditCallbackToken(null, "secret"), false);
  assert.equal(verifyXenditCallbackToken("secret", ""), false);
});

test("only successful GCash captures in PHP are accepted for settlement", () => {
  assert.equal(parseXenditWebhook(captureEvent()).event, "payment.capture");
  assert.throws(
    () => parseXenditWebhook(captureEvent({ currency: "USD" })),
    /PHP/
  );
  assert.throws(
    () => parseXenditWebhook(captureEvent({ channel_code: "CARDS" })),
    /GCash/
  );
  assert.throws(
    () => parseXenditWebhook(captureEvent({ status: "FAILED" })),
    /successful/
  );
});

test("a verified Xendit capture confirms its pending order exactly once", async (t) => {
  const db = await createDatabase(t);
  await db.prepare(
    `INSERT INTO orders (id, status, payment_method, payment_status, total)
     VALUES ($1, $2, $3, $4, $5)`
  ).run(42, "payment_pending", "gcash", "pending", 100);
  const attempt = await prepareXenditPayment(42, "order");
  await saveXenditPaymentRequest(
    attempt.reference_id,
    "pr-test-123",
    "https://checkout.xendit.co/test",
    null,
    null
  );
  const event = captureEvent({ reference_id: attempt.reference_id });

  assert.deepEqual(await handleXenditWebhook(event), { action: "applied" });
  assert.deepEqual(await handleXenditWebhook(event), { action: "duplicate" });

  const order = await db.prepare(
    "SELECT status, payment_status, payment_amount, payment_reference FROM orders WHERE id = $1"
  ).get(42);
  assert.equal(order.status, "confirmed");
  assert.equal(order.payment_status, "verified");
  assert.equal(Number(order.payment_amount), 100);
  assert.equal(order.payment_reference, "py-test-123");
});

