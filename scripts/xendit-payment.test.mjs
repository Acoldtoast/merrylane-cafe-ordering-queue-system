test("development payment status sync settles only an authenticated matching success", async (t) => {
  const db = await createDatabase(t);
  await db.prepare(
    `INSERT INTO orders (id, status, payment_method, payment_status, total)
     VALUES ($1, $2, $3, $4, $5)`
  ).run(46, "payment_pending", "gcash", "pending", 100);
  const attempt = await prepareXenditPayment(46, "order");
  await saveXenditPaymentRequest(
    attempt.reference_id,
    "pr-test-status",
    "https://checkout.xendit.co/test",
    null,
    null
  );

  const originalFetch = globalThis.fetch;
  let status = "PENDING";
  globalThis.fetch = async (url, options) => {
    assert.equal(
      String(url),
      "https://api.xendit.co/v3/payment_requests/pr-test-status"
    );
    assert.equal(
      options.headers.Authorization,
      `Basic ${Buffer.from("test-secret:").toString("base64")}`
    );
    return Response.json({
      payment_request_id: "pr-test-status",
      reference_id: attempt.reference_id,
      type: "PAY",
      country: "PH",
      currency: "PHP",
      channel_code: "GCASH",
      request_amount: 100,
      status,
      latest_payment_id: "py-test-status",
    });
  };
  t.after(() => {
    globalThis.fetch = originalFetch;
  });

  assert.deepEqual(
    await syncXenditPaymentStatus(46, "order", "test-secret"),
    { status: "pending" }
  );
  let order = await db.prepare(
    "SELECT status, payment_status FROM orders WHERE id = $1"
  ).get(46);
  assert.equal(order.status, "payment_pending");
  assert.equal(order.payment_status, "pending");

  status = "SUCCEEDED";
  assert.deepEqual(
    await syncXenditPaymentStatus(46, "order", "test-secret"),
    { status: "succeeded" }
  );
  order = await db.prepare(
    "SELECT status, payment_status, payment_reference FROM orders WHERE id = $1"
  ).get(46);
  assert.equal(order.status, "confirmed");
  assert.equal(order.payment_status, "verified");
  assert.equal(order.payment_reference, "py-test-status");
});

