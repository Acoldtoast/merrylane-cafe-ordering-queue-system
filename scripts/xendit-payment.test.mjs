test("a successful capture records a separate verified GCash balance payment", async (t) => {
  const db = await createDatabase(t);
  await db.prepare(
    `INSERT INTO orders
       (id, status, payment_method, payment_status, total, payment_amount)
     VALUES ($1, $2, $3, $4, $5, $6)`
  ).run(44, "preparing", "gcash", "verified", 130, 100);
  const attempt = await prepareXenditPayment(44, "balance");
  await saveXenditPaymentRequest(
    attempt.reference_id,
    "pr-test-balance",
    "https://checkout.xendit.co/test",
    null,
    null
  );
  const event = captureEvent({
    payment_id: "py-test-balance",
    payment_request_id: "pr-test-balance",
    reference_id: attempt.reference_id,
    request_amount: 30,
    captures: [{ capture_id: "cap-test-balance", capture_amount: 30 }],
  });

  assert.deepEqual(await handleXenditWebhook(event), { action: "applied" });
  assert.deepEqual(await handleXenditWebhook(event), { action: "duplicate" });
  const payments = await db.prepare(
    "SELECT amount, status, payment_reference FROM order_balance_payments WHERE order_id = $1"
  ).all(44);
  assert.equal(payments.length, 1);
  assert.equal(Number(payments[0].amount), 30);
  assert.equal(payments[0].status, "verified");
  assert.equal(payments[0].payment_reference, "py-test-balance");
});

