import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { PGliteDatabase } from "../src/lib/db/pglite.ts";
import {
  ensureEmailOutbox,
  listEmailDeliveries,
  retryFailedEmail,
} from "../src/lib/emailOutbox.ts";

test("email outbox migrates old rows, pages the log, and retries failed mail", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "merrylane-email-outbox-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));

  const database = PGliteDatabase.open(path.join(root, "pgdata"));
  globalThis.__merrylaneDb = database;
  t.after(async () => {
    globalThis.__merrylaneDb = undefined;
    await database.close();
  });

  await database.exec(`
    CREATE TABLE email_notification_outbox (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_key TEXT NOT NULL UNIQUE,
      subject TEXT NOT NULL,
      text_body TEXT NOT NULL,
      html_body TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      attempts INTEGER NOT NULL DEFAULT 0,
      last_error TEXT,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);
  await ensureEmailOutbox();

  const columns = await database
    .prepare("PRAGMA table_info(email_notification_outbox)")
    .all();
  assert.ok(columns.some((column) => column.name === "recipient_email"));
  assert.ok(columns.some((column) => column.name === "manual_retries"));
  assert.ok(columns.some((column) => column.name === "last_error_transient"));

  await database.prepare(
    `INSERT INTO email_notification_outbox
       (event_key, recipient_email, subject, text_body, html_body, status, attempts, last_error)
     VALUES (?, ?, ?, ?, ?, 'failed', 3, ?)`
  ).run(
    "event-1",
    "owner@example.com",
    "Daily sales report",
    "body",
    "<p>body</p>",
    JSON.stringify({
      title: "The mail server rejected the account password.",
      details: "535 invalid login",
      fix: "Check the SMTP app password.",
    })
  );
  await database.prepare(
    `INSERT INTO email_notification_outbox
       (event_key, recipient_email, subject, text_body, html_body, status)
     VALUES (?, ?, ?, ?, ?, 'sent')`
  ).run("event-2", "owner@example.com", "Stock alert", "body", "<p>body</p>");

  const firstPage = await listEmailDeliveries(undefined, 1);
  assert.equal(firstPage.items.length, 1);
  assert.equal(firstPage.hasMore, true);
  assert.equal(firstPage.items[0].subject, "Stock alert");

  const failed = await listEmailDeliveries(firstPage.nextBefore ?? undefined, 1);
  assert.equal(failed.items[0].status, "failed");
  assert.match(failed.items[0].last_error?.title ?? "", /rejected the account password/);

  assert.equal(await retryFailedEmail(failed.items[0].id), true);
  assert.equal(await retryFailedEmail(failed.items[0].id), false);
  const retried = await database
    .prepare(
      "SELECT status, attempts, manual_retries, last_error FROM email_notification_outbox WHERE id = ?"
    )
    .get(failed.items[0].id);
  assert.equal(retried.status, "pending");
  assert.equal(retried.attempts, 0);
  assert.equal(retried.manual_retries, 1);
  assert.match(retried.last_error, /rejected the account password/);

  const retryDelay = await database
    .prepare(
      "SELECT NOW() - (INTERVAL '5 minutes' * POWER(2, 1)) <= NOW() AS elapsed"
    )
    .get();
  assert.equal(retryDelay.elapsed, true);
});
