async function createAuthDatabase(t, prefix) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), `merrylane-${prefix}-`));
  const database = PGliteDatabase.open(path.join(root, "pgdata"));
  globalThis.__merrylaneDb = database;
  t.after(async () => {
    globalThis.__merrylaneDb = undefined;
    await database.close();
    await fs.rm(root, { recursive: true, force: true });
  });

  await database.exec(`
    CREATE TABLE users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      username TEXT,
      email TEXT NOT NULL UNIQUE,
      role TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      contact_number TEXT,
      address TEXT,
      duty_hours TEXT,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
      is_active INTEGER NOT NULL DEFAULT 1,
      last_login_at TEXT,
      last_logout_at TEXT,
      duty_minutes INTEGER NOT NULL DEFAULT 0,
      session_id TEXT
    )
  `);
  await database.exec(`
    CREATE TABLE activity_logs (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER,
      actor_name TEXT,
      actor_role TEXT,
      area TEXT NOT NULL,
      action TEXT NOT NULL,
      summary TEXT NOT NULL,
      entity_type TEXT,
      entity_id INTEGER,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);
  await database.exec(`
    CREATE TABLE settings (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    )
  `);
  return database;
}

function loginRequest(username, password, deviceId, remember) {
  const headers = new Headers({ "content-type": "application/json" });
  if (deviceId) {
    headers.set("cookie", `${LOGIN_DEVICE_COOKIE}=${deviceId}`);
  }
  return new NextRequest("http://localhost/api/auth/login", {
    method: "POST",
    headers,
    body: JSON.stringify({ username, password, remember }),
  });
}

function recoveryVerifyRequest(username, code) {
  return new Request("http://localhost/api/auth/password-recovery/verify", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ username, code }),
  });
}

function recoveryCodeRequest(username) {
  return new NextRequest("http://localhost/api/auth/password-recovery", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ username }),
  });
}

function staffIdleRequest(token, lastActivityAt) {
  return new Request("http://localhost/api/auth/staff-idle", {
    method: "POST",
    headers: {
      cookie: `auth-staff-token=${token}`,
      "content-type": "application/json",
    },
    body: JSON.stringify({ last_activity_at: lastActivityAt }),
  });
}

test("login failures share a device streak across emails and successful login clears it", async (t) => {
  const database = await createAuthDatabase(t, "device-auth");
  const { hashPassword } = await import("../src/lib/models.ts");
  const staffPassword = "staff-original-password";
  await database
    .prepare(
      `INSERT INTO users (name, username, email, role, password_hash)
       VALUES (?, ?, ?, ?, ?)`
    )
    .run(
      "Staff Member",
      "staff-member-merrylane",
      "staff@example.test",
      "staff",
      hashPassword(staffPassword)
    );

  const { POST } = await import("../src/app/api/auth/login/route.ts");
  let deviceId;
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    const response = await POST(
      loginRequest(`unknown-${attempt}`, "wrong-password", deviceId)
    );
    assert.equal(response.status, 401);
    const data = await response.json();
    assert.equal(data.failed_attempts, attempt);
    if (attempt === 1) {
      deviceId = response.cookies.get(LOGIN_DEVICE_COOKIE)?.value;
      assert.ok(deviceId);
    }
  }

  const successfulLogin = await POST(
    loginRequest("staff-member-merrylane", staffPassword, deviceId, true)
  );
  assert.equal(successfulLogin.status, 200);
  assert.equal((await successfulLogin.json()).success, true);
  const { JWT_SECRET } = await import("../src/lib/auth.ts");
  const rememberedToken =
    successfulLogin.cookies.get("auth-staff-token")?.value;
  assert.ok(rememberedToken);
  const { payload } = await jwtVerify(
    rememberedToken,
    new TextEncoder().encode(JWT_SECRET)
  );
  assert.equal(Number(payload.exp) - Number(payload.iat), 12 * 60 * 60);

  const { getDeviceLoginRestriction } = await import(
    "../src/lib/authSecurity.ts"
  );
  assert.deepEqual(await getDeviceLoginRestriction(deviceId), {
    status: "allowed",
    failedAttempts: 0,
  });

  for (let attempt = 1; attempt <= 5; attempt += 1) {
    const response = await POST(
      loginRequest(`other-unknown-${attempt}`, "wrong-password", deviceId)
    );
    const data = await response.json();
    if (attempt < 5) {
      assert.equal(response.status, 401);
      assert.equal(data.failed_attempts, attempt);
    } else {
      assert.equal(response.status, 429);
      assert.equal(data.failed_attempts, 5);
      assert.equal(data.retry_after_seconds, 60);
      assert.equal(
        data.error,
        "Too many sign-in attempts. Please try again in 1 minute."
      );
    }
  }
});

test("device cooldown escalates to a next-day lock and resets the streak at Manila midnight", async (t) => {
  const database = await createAuthDatabase(t, "device-cooldown");
  const {
    getNextManilaMidnight,
    getDeviceLoginRestriction,
    recordDeviceLoginFailure,
  } = await import("../src/lib/authSecurity.ts");
  let now = new Date("2026-01-01T00:00:00.000Z");
  let restriction;

  for (let attempt = 1; attempt <= 5; attempt += 1) {
    restriction = await recordDeviceLoginFailure("device-a", now);
    assert.equal(restriction.failedAttempts, attempt);
  }
  assert.equal(restriction.status, "cooldown");
  assert.equal(restriction.retryAfterSeconds, 60);

  let previousCooldownMinutes = 1;
  let expectedFailedAttempts = 5;
  for (const cooldownMinutes of [2, 3, 5]) {
    now = new Date(now.getTime() + previousCooldownMinutes * 60_000 + 1);
    restriction = await recordDeviceLoginFailure("device-a", now);
    expectedFailedAttempts += 1;
    assert.equal(restriction.status, "allowed");
    assert.equal(restriction.failedAttempts, expectedFailedAttempts);

    now = new Date(now.getTime() + 1);
    restriction = await recordDeviceLoginFailure("device-a", now);
    expectedFailedAttempts += 1;
    assert.equal(restriction.status, "cooldown");
    assert.equal(restriction.failedAttempts, expectedFailedAttempts);
    assert.equal(restriction.retryAfterSeconds, cooldownMinutes * 60);
    previousCooldownMinutes = cooldownMinutes;
  }

  assert.deepEqual(await getDeviceLoginRestriction("device-b", now), {
    status: "allowed",
    failedAttempts: 0,
  });
  assert.deepEqual(await getDeviceLoginRestriction("device-a", now), {
    status: "cooldown",
    failedAttempts: 11,
    retryAfterSeconds: 300,
  });
  now = new Date(now.getTime() + 5 * 60_000 + 1);
  restriction = await recordDeviceLoginFailure("device-a", now);
  assert.equal(restriction.status, "allowed");
  assert.equal(restriction.failedAttempts, 12);

  now = new Date(now.getTime() + 1);
  restriction = await recordDeviceLoginFailure("device-a", now);
  assert.equal(restriction.status, "cooldown");
  assert.equal(restriction.failedAttempts, 13);
  assert.equal(restriction.untilNextDay, true);
  assert.equal(
    restriction.retryAfterSeconds,
    Math.ceil((getNextManilaMidnight(now).getTime() - now.getTime()) / 1000)
  );
  assert.deepEqual(await getDeviceLoginRestriction("device-a", now), {
    status: "cooldown",
    failedAttempts: 13,
    retryAfterSeconds: restriction.retryAfterSeconds,
    untilNextDay: true,
  });

  const nextDay = getNextManilaMidnight(now);
  assert.deepEqual(await getDeviceLoginRestriction("device-a", nextDay), {
    status: "allowed",
    failedAttempts: 0,
  });
  assert.deepEqual(await recordDeviceLoginFailure("device-a", nextDay), {
    status: "allowed",
    failedAttempts: 1,
  });

  const activity = await database
    .prepare("SELECT action, summary FROM activity_logs ORDER BY id")
    .all();
  assert.ok(activity.some((entry) => entry.action === "auth.login_cooldown"));
});

