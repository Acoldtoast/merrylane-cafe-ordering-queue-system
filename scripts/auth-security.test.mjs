test("password recovery works for staff and administrators and clears the requesting device", async (t) => {
  const database = await createAuthDatabase(t, "account-recovery");
  const { hashPassword, verifyPassword } = await import("../src/lib/models.ts");
  const {
    createUserRecoveryCode,
    getDeviceLoginRestriction,
    markUserRecoveryCodeSent,
    recordDeviceLoginFailure,
    resetUserPasswordWithCode,
  } = await import("../src/lib/authSecurity.ts");
  const { POST: verifyRecoveryCodeRequest } = await import(
    "../src/app/api/auth/password-recovery/verify/route.ts"
  );
  const users = [
    {
      name: "Staff Member",
      username: "staff-member-merrylane",
      email: "staff@example.test",
      role: "staff",
      password: "original-staff-password",
    },
    {
      name: "Administrator",
      username: "recovery-admin-merrylane",
      email: "admin@example.test",
      role: "admin",
      password: "original-admin-password",
    },
  ];
  const userIds = {};
  for (const user of users) {
    userIds[user.role] = Number(
      (
        await database
          .prepare(
            `INSERT INTO users (name, username, email, role, password_hash)
             VALUES (?, ?, ?, ?, ?)`
          )
          .run(
            user.name,
            user.username,
            user.email,
            user.role,
            hashPassword(user.password)
          )
      ).lastInsertRowid
    );
  }

  let now = new Date();
  await recordDeviceLoginFailure("staff-device", now);
  const staffRecovery = await createUserRecoveryCode(userIds.staff, now);
  assert.equal(staffRecovery.status, "created");
  if (staffRecovery.status !== "created") return;
  await markUserRecoveryCodeSent(
    userIds.staff,
    new Date(now.getTime() + 10_000)
  );
  const throttledRecovery = await createUserRecoveryCode(
    userIds.staff,
    new Date(now.getTime() + 30_000)
  );
  assert.deepEqual(throttledRecovery, {
    status: "throttled",
    retryAfterSeconds: 40,
  });

  const wrongCode = staffRecovery.code === "000000" ? "111111" : "000000";
  assert.equal(
    (
      await verifyRecoveryCodeRequest(
        recoveryVerifyRequest("staff-member-merrylane", wrongCode)
      )
    ).status,
    400
  );
  const verifiedCodeResponse = await verifyRecoveryCodeRequest(
    recoveryVerifyRequest("staff-member-merrylane", staffRecovery.code)
  );
  assert.equal(verifiedCodeResponse.status, 200);
  assert.equal((await verifiedCodeResponse.json()).success, true);
  assert.equal(
    (
      await resetUserPasswordWithCode(
        userIds.staff,
        staffRecovery.code,
        users[0].password,
        { now: new Date(now.getTime() + 33_000) }
      )
    ).status,
    "password_unchanged"
  );
  assert.equal(
    (
      await resetUserPasswordWithCode(
        userIds.staff,
        staffRecovery.code,
        "new-staff-password",
        {
          now: new Date(now.getTime() + 34_000),
          deviceId: "staff-device",
        }
      )
    ).status,
    "success"
  );
  assert.deepEqual(await getDeviceLoginRestriction("staff-device", now), {
    status: "allowed",
    failedAttempts: 0,
  });

  now = new Date(now.getTime() + 60_000);
  const adminRecovery = await createUserRecoveryCode(userIds.admin, now);
  assert.equal(adminRecovery.status, "created");
  if (adminRecovery.status !== "created") return;
  assert.equal(
    (
      await resetUserPasswordWithCode(
        userIds.admin,
        adminRecovery.code,
        "new-admin-password",
        { now: new Date(now.getTime() + 1_000) }
      )
    ).status,
    "success"
  );

  for (const user of users) {
    const updatedUser = await database
      .prepare("SELECT password_hash FROM users WHERE id = ?")
      .get(userIds[user.role]);
    const expectedPassword =
      user.role === "staff" ? "new-staff-password" : "new-admin-password";
    assert.equal(verifyPassword(expectedPassword, updatedUser.password_hash), true);
    assert.equal(verifyPassword(user.password, updatedUser.password_hash), false);
  }

  const activity = await database
    .prepare("SELECT action FROM activity_logs ORDER BY id")
    .all();
  assert.ok(activity.some((entry) => entry.action === "auth.password_recovered"));
});

test("admin recovery sends to the saved general email and enforces the resend cooldown", async (t) => {
  const database = await createAuthDatabase(t, "admin-recovery-email");
  const { hashPassword } = await import("../src/lib/models.ts");
  const accountUsername = "admin-recovery-merrylane";
  const accountEmail = "admin@example.test";
  const generalEmail = "admin-contact@example.test";
  const user = await database
    .prepare(
      `INSERT INTO users (name, username, email, role, password_hash)
       VALUES (?, ?, ?, ?, ?)
       RETURNING id`
    )
    .get(
      "Administrator",
      accountUsername,
      accountEmail,
      "admin",
      hashPassword("admin-password")
    );
  await database
    .prepare("INSERT INTO settings (key, value) VALUES (?, ?)")
    .run(`admin_notification_email_${user.id}`, generalEmail);
  await database
    .prepare("INSERT INTO settings (key, value) VALUES (?, ?)")
    .run(
      "email_notifications_config",
      JSON.stringify({
        smtpHost: "smtp.example.test",
        smtpPort: 587,
        smtpSecure: false,
        smtpUser: "",
        fromName: "Merrylane Cafe",
        fromEmail: "noreply@example.test",
        subscriptions: [],
        sendTime: "08:00",
      })
    );

  const nodemailer = (await import("nodemailer")).default;
  const originalCreateTransport = nodemailer.createTransport;
  const sentMessages = [];
  let failNextSend = true;
  nodemailer.createTransport = () => ({
    sendMail: async (message) => {
      if (failNextSend) {
        failNextSend = false;
        throw new Error("Test SMTP failure");
      }
      sentMessages.push(message);
    },
    close() {},
  });
  t.after(() => {
    nodemailer.createTransport = originalCreateTransport;
  });

  const { POST: requestRecoveryCode } = await import(
    "../src/app/api/auth/password-recovery/route.ts"
  );
  const failedResponse = await requestRecoveryCode(
    recoveryCodeRequest(accountUsername)
  );
  // A delivery failure must look identical to a normal send so it cannot be
  // used to confirm that an account exists.
  assert.equal(failedResponse.status, 200);
  const failedResult = await failedResponse.json();
  assert.equal(failedResult.success, true);
  assert.ok(failedResult.message);
  assert.equal(failedResult.retry_after_seconds, 60);
  assert.equal(sentMessages.length, 0);
  const failedCode = await database
    .prepare(
      `SELECT recovery_code_hash, recovery_code_sent_at
       FROM admin_auth_security WHERE user_id = ?`
    )
    .get(user.id);
  assert.equal(failedCode.recovery_code_hash, null);
  assert.equal(failedCode.recovery_code_sent_at, null);

  const firstResponse = await requestRecoveryCode(
    recoveryCodeRequest(accountUsername)
  );
  assert.equal(firstResponse.status, 200);
  const firstResult = await firstResponse.json();
  assert.equal(firstResult.retry_after_seconds, 60);
  assert.equal(sentMessages.length, 1);
  assert.equal(sentMessages[0].to, generalEmail);

  const unknownAccountResponse = await requestRecoveryCode(
    recoveryCodeRequest("missing-merrylane")
  );
  assert.equal(unknownAccountResponse.status, 200);
  const unknownResult = await unknownAccountResponse.json();
  assert.deepEqual(unknownResult, firstResult);

  const resendResponse = await requestRecoveryCode(
    recoveryCodeRequest(accountUsername)
  );
  assert.equal(resendResponse.status, 200);
  const resendResult = await resendResponse.json();
  assert.equal(resendResult.throttled, undefined);
  assert.equal(resendResult.retry_after_seconds, 60);
  // Throttled requests look the same as a send and do not deliver another mail.
  assert.deepEqual(resendResult, firstResult);
  assert.equal(sentMessages.length, 1);
});

