import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { PGliteDatabase, convertSql } from "../src/lib/db/pglite.ts";

test("PGlite adapter handles async statements, IDs, placeholders, and transactions", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "merrylane-pglite-adapter-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));

  const database = PGliteDatabase.open(path.join(root, "pgdata"));
  try {
    await database.exec(
      "CREATE TABLE products (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE)"
    );
    const insert = await database
      .prepare("INSERT INTO products (name) VALUES (?)")
      .run("coffee");
    assert.equal(insert.lastInsertRowid, 1);
    assert.equal(insert.changes, 1);

    const row = await database
      .prepare("SELECT '?' AS marker, name FROM products WHERE id = ?")
      .get(1);
    assert.deepEqual(row, { marker: "?", name: "coffee" });
    assert.deepEqual(
      (await database.prepare("PRAGMA table_info(products)").all()).map(
        (column) => column.name
      ),
      ["id", "name"]
    );

    const ignored = await database
      .prepare("INSERT OR IGNORE INTO products (name) VALUES (?)")
      .run("coffee");
    assert.equal(ignored.changes, 0);

    await assert.rejects(
      database.transaction(async (transaction) => {
        await transaction
          .prepare("INSERT INTO products (name) VALUES (?)")
          .run("tea");
        throw new Error("rollback");
      }),
      /rollback/
    );
    assert.equal(
      await database
        .prepare("SELECT COUNT(*)::integer AS count FROM products")
        .get().then((result) => result.count),
      1
    );

    const calendar = await database
      .prepare(
        "SELECT date(?, '+1 day') AS next_day, datetime('now', 'localtime', '-90 minutes') AS recent, strftime('%H', ?) AS hour, MAX(1, 2) AS larger, MIN(1, 2) AS smaller"
      )
      .get("2025-02-28", "2025-02-28 07:45:00");
    assert.equal(calendar.next_day, "2025-03-01");
    assert.match(calendar.recent, /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/);
    assert.equal(calendar.hour, "07");
    assert.equal(calendar.larger, 2);
    assert.equal(calendar.smaller, 1);
    const shifted = await database
      .prepare("SELECT date(?, ?) AS start_date")
      .get("2025-03-15", "-14 days");
    assert.equal(shifted.start_date, "2025-03-01");
    const elapsed = await database
      .prepare(
        "SELECT (julianday('now', 'localtime') - julianday(?)) * 1440 AS minutes"
      )
      .get("2020-01-01 00:00:00");
    assert.ok(Number.isFinite(Number(elapsed.minutes)));
    assert.ok(Number(elapsed.minutes) > 0);
  } finally {
    await database.close();
  }
});

test("PGlite preserves the existing database when an abort occurs", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "merrylane-pglite-recovery-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));

  const database = PGliteDatabase.open(path.join(root, "pgdata"));
  t.after(async () => {
    await database.close();
  });

  await database.exec("CREATE TABLE demo (id INTEGER PRIMARY KEY, name TEXT)");
  await database.prepare("INSERT INTO demo (id, name) VALUES (?, ?)").run(1, "preserved");
  const originalReady = database["ready"];
  try {
    database["ready"] = Promise.reject(
      new Error("Aborted(). Build with -sASSERTIONS for more info.")
    );
    await assert.rejects(
      database.exec("CREATE TABLE should_not_exist (id INTEGER)"),
      /Aborted/
    );
  } finally {
    database["ready"] = originalReady;
  }
  const row = await database.prepare("SELECT name FROM demo WHERE id = ?").get(1);
  assert.equal(row.name, "preserved");
  assert.deepEqual((await fs.readdir(root)).filter((name) => name.includes("-corrupt-")), []);
});

test("SQL placeholder conversion skips quoted strings and comments", () => {
  assert.equal(
    convertSql("SELECT '?', `column`, ? -- ?\n/* ? */ WHERE id = ?"),
    'SELECT \'?\', "column", $1 -- ?\n/* ? */ WHERE id = $2'
  );
  assert.equal(
    convertSql("INSERT OR IGNORE INTO items (name) VALUES (?)"),
    "INSERT INTO items (name) VALUES ($1) ON CONFLICT DO NOTHING"
  );
  const translated = convertSql(
    "SELECT date(orders.created_at, '+1 day'), julianday(created_at), julianday('now', 'localtime'), MAX(login_at, date(?))"
  );
  assert.match(translated, /to_char\(\(\(orders\.created_at\)::date/);
  assert.match(translated, /EXTRACT\(EPOCH FROM \(created_at\)::timestamp\)/);
  assert.match(
    translated,
    /EXTRACT\(EPOCH FROM timezone\('Asia\/Manila', CURRENT_TIMESTAMP\)\)/
  );
  assert.match(translated, /GREATEST\(login_at, to_char\(/);
  assert.throws(
    () => convertSql("INSERT OR REPLACE INTO items (id) VALUES (?)"),
    /must be rewritten/
  );
});
