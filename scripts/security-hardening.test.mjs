process.env.JWT_SECRET = "test-only-hardening-secret-do-not-use-in-production";

async function createBaseDatabase(t, prefix) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), `merrylane-${prefix}-`));
  const database = PGliteDatabase.open(path.join(root, "pgdata"));
  globalThis.__merrylaneDb = database;
  t.after(async () => {
    globalThis.__merrylaneDb = undefined;
    await database.close();
    await fs.rm(root, { recursive: true, force: true });
  });
  await database.exec(`
    CREATE TABLE users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      username TEXT,
      email TEXT NOT NULL UNIQUE,
      role TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      contact_number TEXT,
      address TEXT,
      duty_hours TEXT,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
      is_active INTEGER NOT NULL DEFAULT 1,
      last_login_at TEXT,
      last_logout_at TEXT,
      duty_minutes INTEGER NOT NULL DEFAULT 0,
      session_id TEXT
    )
  `);
  await database.exec(`
    CREATE TABLE settings (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    )
  `);
  await database.exec(`
    CREATE TABLE activity_logs (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER,
      actor_name TEXT,
      actor_role TEXT,
      area TEXT NOT NULL,
      action TEXT NOT NULL,
      summary TEXT NOT NULL,
      entity_type TEXT,
      entity_id INTEGER,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);
  return database;
}

test("JWT_SECRET has no insecure default and getJwtSecret returns the configured secret", () => {
  const { JWT_SECRET, getJwtSecret } = import("../src/lib/auth.ts");
  // eslint-disable-next-line no-return-await
  return (async () => {
    const { JWT_SECRET, getJwtSecret } = await import("../src/lib/auth.ts");
    assert.notEqual(
      JWT_SECRET,
      "merrylane-secret-change-me-in-production",
      "the shipped default must not remain usable"
    );
    assert.equal(getJwtSecret(), process.env.JWT_SECRET);
  })();
});

test("cafe network trust is based on the socket address, not forged headers", async () => {
  const { isCafeNetworkFromIp } = await import("../src/lib/network.ts");
  // Private LAN addresses (the cafe router's address seen by the server).
  assert.equal(isCafeNetworkFromIp("192.168.1.42"), true);
  assert.equal(isCafeNetworkFromIp("10.0.0.1"), true);
  assert.equal(isCafeNetworkFromIp("172.16.0.5"), true);
  assert.equal(isCafeNetworkFromIp("127.0.0.1"), true);
  assert.equal(isCafeNetworkFromIp("::1"), true);
  // Public internet addresses are never the cafe network.
  assert.equal(isCafeNetworkFromIp("203.0.113.44"), false);
  assert.equal(isCafeNetworkFromIp("8.8.8.8"), false);
  assert.equal(isCafeNetworkFromIp(""), false);
});

test("login failures are locked by username even when the device cookie rotates", async (t) => {
  await createBaseDatabase(t, "username-lockout");
  const {
    getUsernameLoginRestriction,
    recordUsernameLoginFailure,
    clearUsernameLoginFailures,
  } = await import("../src/lib/authSecurity.ts");
  const username = "jane-merrylane";
  let now = new Date("2026-01-01T00:00:00.000Z");

  // Four failures against the same username are allowed, each with a
  // different device ID an attacker could rotate freely.
  let restriction;
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    restriction = await recordUsernameLoginFailure(username, now);
    assert.equal(restriction.failedAttempts, attempt);
    assert.equal(restriction.status, "allowed");
  }
  // The fifth failure locks the username regardless of device.
  now = new Date(now.getTime() + 1);
  restriction = await recordUsernameLoginFailure(username, now);
  assert.equal(restriction.status, "cooldown");
  assert.equal(restriction.failedAttempts, 5);
  assert.equal(restriction.retryAfterSeconds, 60);

  // A fresh device does not reset the username streak.
  restriction = await getUsernameLoginRestriction(username, now);
  assert.equal(restriction.status, "cooldown");
  assert.equal(restriction.failedAttempts, 5);

  // Once the cooldown expires the next failure is allowed again.
  now = new Date(now.getTime() + 61_000);
  restriction = await recordUsernameLoginFailure(username, now);
  assert.equal(restriction.status, "allowed");
  assert.equal(restriction.failedAttempts, 6);

  await clearUsernameLoginFailures(username);
  restriction = await getUsernameLoginRestriction(username, now);
  assert.deepEqual(restriction, { status: "allowed", failedAttempts: 0 });
});

test("online restore is disabled for valid and malformed names and requires an administrator", async (t) => {
  const database = await createBaseDatabase(t, "backup-restore");
  const { hashPassword } = await import("../src/lib/models.ts");
  const { getJwtSecret } = await import("../src/lib/auth.ts");
  const { UserModel } = await import("../src/lib/models.ts");
  await UserModel.ensureColumns();

  const adminId = Number(
    (
      await database
        .prepare(
          `INSERT INTO users (name, username, email, role, password_hash, session_id)
           VALUES (?, ?, ?, ?, ?, ?)
           RETURNING id`
        )
        .run(
          "Administrator",
          "admin-restore-merrylane",
          "admin-restore@example.test",
          "admin",
          hashPassword("admin-password"),
          "restore-session-1"
        )
    ).lastInsertRowid
  );
  const token = await new SignJWT({
    userId: adminId,
    role: "admin",
    sid: "restore-session-1",
  })
    .setProtectedHeader({ alg: "HS256" })
    .setIssuedAt()
    .sign(new TextEncoder().encode(getJwtSecret()));

  const { POST: restore } = await import(
    "../src/app/api/admin/backup/restore/route.ts"
  );

  function restoreRequest(body) {
    const url = new URL("http://localhost/api/admin/backup/restore");
    return new Request(url, {
      method: "POST",
      headers: {
        cookie: `auth-admin-token=${token}`,
        "content-type": "application/json",
      },
      body: JSON.stringify(body),
    });
  }

  const badNames = [
    "backup-../../../etc",
    "backup-../x",
    "backup-20260101-120000-extra",
    "not-backup",
    "",
    "../../../data/backups/backup-20260101-120000",
  ];
  for (const name of badNames) {
    const response = await restore(restoreRequest({ backup_name: name }));
    assert.equal(
      response.status,
      503,
      `online restore must be disabled for ${JSON.stringify(name)}`
    );
    assert.equal((await response.json()).success, false);
  }

  // A well-formed name is also blocked before any filesystem mutation.
  const missingResponse = await restore(
    restoreRequest({ backup_name: "backup-20260101-120000" })
  );
  assert.equal(missingResponse.status, 503);
  assert.equal((await missingResponse.json()).success, false);
  const account = await database.prepare("SELECT username FROM users WHERE id = ?").get(adminId);
  assert.equal(account.username, "admin-restore-merrylane");

  // An unauthenticated request is rejected before any name handling.
  const unauth = new Request("http://localhost/api/admin/backup/restore", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ backup_name: "backup-../../../x" }),
  });
  const unauthResponse = await restore(unauth);
  assert.equal(unauthResponse.status, 403);
});

test("login route locks by username across device rotation and clears both lockouts on success", async (t) => {
  const database = await createBaseDatabase(t, "login-clears-lockouts");
  const { hashPassword } = await import("../src/lib/models.ts");
  await database
    .prepare(
      `INSERT INTO users (name, username, email, role, password_hash)
       VALUES (?, ?, ?, ?, ?)`
    )
    .run(
      "Staff Member",
      "staff-member-merrylane",
      "staff@example.test",
      "staff",
      hashPassword("staff-password")
    );

  const { POST } = await import("../src/app/api/auth/login/route.ts");
  const post = (username, password, deviceId) => {
    const headers = new Headers({ "content-type": "application/json" });
    if (deviceId) headers.set("cookie", `${LOGIN_DEVICE_COOKIE}=${deviceId}`);
    return POST(
      new NextRequest("http://localhost/api/auth/login", {
        method: "POST",
        headers,
        body: JSON.stringify({ username, password }),
      })
    );
  };

  // Four wrong passwords are rejected; the fifth locks the username even
  // though the device cookie rotated.
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    assert.equal(
      (await post("staff-member-merrylane", "wrong", "attacker-device-1")).status,
      401
    );
  }
  const lockedResponse = await post(
    "staff-member-merrylane",
    "wrong",
    "attacker-device-2"
  );
  assert.equal(lockedResponse.status, 429);

  // Clearing both lockouts (as a successful password reset does) lets the
  // real password sign in again.
  const {
    clearDeviceLoginFailures,
    clearUsernameLoginFailures,
  } = await import("../src/lib/authSecurity.ts");
  await clearDeviceLoginFailures("attacker-device-1");
  await clearDeviceLoginFailures("attacker-device-2");
  await clearUsernameLoginFailures("staff-member-merrylane");

  const successResponse = await post(
    "staff-member-merrylane",
    "staff-password",
    "attacker-device-1"
  );
  assert.equal(successResponse.status, 200);
  assert.equal((await successResponse.json()).success, true);

  const {
    getDeviceLoginRestriction,
    getUsernameLoginRestriction,
  } = await import("../src/lib/authSecurity.ts");
  assert.deepEqual(await getDeviceLoginRestriction("attacker-device-1"), {
    status: "allowed",
    failedAttempts: 0,
  });
  assert.deepEqual(await getUsernameLoginRestriction("staff-member-merrylane"), {
    status: "allowed",
    failedAttempts: 0,
  });
});
