import { getDb } from "@/lib/db";

export interface EmailDeliveryError {
  title: string;
  details: string | null;
  fix: string | null;
}

export interface EmailDeliveryLogEntry {
  id: number;
  recipient_email: string | null;
  subject: string;
  status: "pending" | "sending" | "sent" | "failed";
  attempts: number;
  manual_retries: number;
  last_error: EmailDeliveryError | null;
  created_at: string;
  updated_at: string;
}

let outboxInitialization: Promise<void> | null = null;

function parseDeliveryError(value: string | null): EmailDeliveryError | null {
  if (!value) return null;

  try {
    const parsed: unknown = JSON.parse(value);
    if (typeof parsed === "object" && parsed !== null && !Array.isArray(parsed)) {
      const error = parsed as Record<string, unknown>;
      if (typeof error.title === "string") {
        return {
          title: error.title,
          details: typeof error.details === "string" ? error.details : null,
          fix: typeof error.fix === "string" ? error.fix : null,
        };
      }
    }
  } catch {
    return { title: value, details: null, fix: null };
  }

  return { title: value, details: null, fix: null };
}

async function initializeEmailOutbox(): Promise<void> {
  const db = getDb();
  await db.exec(`
    CREATE TABLE IF NOT EXISTS email_notification_outbox (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_key TEXT NOT NULL UNIQUE,
      recipient_email TEXT,
      subject TEXT NOT NULL,
      text_body TEXT NOT NULL,
      html_body TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sending', 'sent', 'failed')),
      attempts INTEGER NOT NULL DEFAULT 0,
      manual_retries INTEGER NOT NULL DEFAULT 0,
      last_error TEXT,
      last_error_transient BOOLEAN NOT NULL DEFAULT TRUE,
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP),
      updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP)
    );
    CREATE INDEX IF NOT EXISTS idx_email_outbox_status_updated
      ON email_notification_outbox(status, updated_at);
    CREATE INDEX IF NOT EXISTS idx_email_outbox_id_desc
      ON email_notification_outbox(id DESC);
  `);
  const columns = (await db
    .prepare("PRAGMA table_info(email_notification_outbox)")
    .all()) as { name: string }[];

  if (!columns.some((column) => column.name === "recipient_email")) {
    await db.exec(
      "ALTER TABLE email_notification_outbox ADD COLUMN recipient_email TEXT"
    );
  }
  if (!columns.some((column) => column.name === "manual_retries")) {
    await db.exec(
      "ALTER TABLE email_notification_outbox ADD COLUMN manual_retries INTEGER NOT NULL DEFAULT 0"
    );
  }
  if (!columns.some((column) => column.name === "last_error_transient")) {
    await db.exec(
      "ALTER TABLE email_notification_outbox ADD COLUMN last_error_transient BOOLEAN NOT NULL DEFAULT TRUE"
    );
  }
}

export function ensureEmailOutbox(): Promise<void> {
  if (!outboxInitialization) {
    outboxInitialization = initializeEmailOutbox().catch((error: unknown) => {
      outboxInitialization = null;
      throw error;
    });
  }
  return outboxInitialization;
}

export async function listEmailDeliveries(
  beforeId: number | undefined,
  limit: number
): Promise<{ items: EmailDeliveryLogEntry[]; hasMore: boolean; nextBefore: number | null }> {
  const query = beforeId === undefined
    ? `SELECT id, recipient_email, subject, status, attempts, manual_retries,
              last_error, created_at, updated_at
       FROM email_notification_outbox
       ORDER BY id DESC
       LIMIT ?`
    : `SELECT id, recipient_email, subject, status, attempts, manual_retries,
              last_error, created_at, updated_at
       FROM email_notification_outbox
       WHERE id < ?
       ORDER BY id DESC
       LIMIT ?`;
  const parameters = beforeId === undefined
    ? [limit + 1]
    : [beforeId, limit + 1];
  const rows = (await getDb()
    .prepare(query)
    .all(...parameters)) as (Omit<EmailDeliveryLogEntry, "last_error"> & {
    last_error: string | null;
  })[];
  const hasMore = rows.length > limit;
  const items = rows.slice(0, limit).map((row) => ({
    ...row,
    last_error: parseDeliveryError(row.last_error),
  }));
  return {
    items,
    hasMore,
    nextBefore: hasMore && items.length > 0 ? items[items.length - 1].id : null,
  };
}

export async function retryFailedEmail(id: number): Promise<boolean> {
  const result = await getDb()
    .prepare(
      `UPDATE email_notification_outbox
       SET status = 'pending', attempts = 0, manual_retries = manual_retries + 1,
           last_error_transient = TRUE, updated_at = CURRENT_TIMESTAMP
       WHERE id = ? AND status = 'failed'`
    )
    .run(id);
  return Number(result.changes) === 1;
}

export async function correctRecipientEmail(
  oldEmail: string,
  newEmail: string
): Promise<number> {
  const result = await getDb()
    .prepare(
      `UPDATE email_notification_outbox
       SET recipient_email = ?, updated_at = CURRENT_TIMESTAMP
       WHERE recipient_email = ?`
    )
    .run(newEmail, oldEmail);
  return Number(result.changes);
}
