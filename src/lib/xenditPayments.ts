import { randomUUID, timingSafeEqual } from "node:crypto";
import { isIP } from "node:net";
import { networkInterfaces } from "node:os";
import { getDb } from "@/lib/db";
import { isPrivateAddress } from "@/lib/network";

export type XenditPaymentKind = "order" | "balance";

type CaptureEvent = {
  event: "payment.capture";
  data: {
    payment_id: string;
    payment_request_id: string;
    reference_id: string;
    request_amount: number;
    capture_id: string;
    capture_amount: number;
  };
};

type StatusEvent = {
  event: "payment.failure" | "payment_request.expiry";
  data: {
    payment_request_id: string;
    reference_id: string;
  };
};

type ParsedWebhook = CaptureEvent | StatusEvent | { event: "ignored" };

export class XenditPaymentError extends Error {
  readonly status: number;

  constructor(
    message: string,
    status = 400
  ) {
    super(message);
    this.name = "XenditPaymentError";
    this.status = status;
  }
}

const tableReady = new WeakMap<object, Promise<void>>();
const CHECKOUT_WINDOW = "INTERVAL '5 minutes'";

export async function ensureXenditPaymentTable() {
  const db = getDb();
  const existing = tableReady.get(db);
  if (existing) return existing;

  const ready = db.exec(`
    CREATE TABLE IF NOT EXISTS xendit_payment_requests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      reference_id TEXT NOT NULL UNIQUE,
      payment_request_id TEXT UNIQUE,
      payment_id TEXT UNIQUE,
      capture_id TEXT UNIQUE,
      order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
      payment_kind TEXT NOT NULL CHECK (payment_kind IN ('order', 'balance')),
      amount NUMERIC(12, 2) NOT NULL,
      currency TEXT NOT NULL DEFAULT 'PHP',
      status TEXT NOT NULL CHECK (
        status IN (
          'creating',
          'pending',
          'failed',
          'expired',
          'mismatched',
          'succeeded',
          'succeeded_unapplied'
        )
      ),
      checkout_url TEXT,
      checkout_mobile_url TEXT,
      checkout_qr_string TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    ALTER TABLE xendit_payment_requests
      ADD COLUMN IF NOT EXISTS checkout_mobile_url TEXT;
    ALTER TABLE xendit_payment_requests
      ADD COLUMN IF NOT EXISTS checkout_qr_string TEXT;
    CREATE INDEX IF NOT EXISTS idx_xendit_payment_requests_order
      ON xendit_payment_requests(order_id, payment_kind, created_at DESC);
  `);
  tableReady.set(db, ready);
  try {
    await ready;
  } catch (error) {
    tableReady.delete(db);
    throw error;
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function requiredString(
  value: unknown,
  field: string
): string {
  if (typeof value !== "string" || !value.trim()) {
    throw new XenditPaymentError(`Xendit webhook is missing ${field}.`, 400);
  }
  return value;
}

export function verifyXenditCallbackToken(
  received: string | null,
  expected: string | undefined
): boolean {
  if (!received || !expected) return false;
  const receivedBytes = Buffer.from(received, "utf8");
  const expectedBytes = Buffer.from(expected, "utf8");
  return (
    receivedBytes.length === expectedBytes.length &&
    timingSafeEqual(receivedBytes, expectedBytes)
  );
}

export function parseXenditWebhook(value: unknown): ParsedWebhook {
  if (!isRecord(value) || typeof value.event !== "string") {
    throw new XenditPaymentError("Invalid Xendit webhook payload.", 400);
  }
  if (value.event !== "payment.capture" &&
      value.event !== "payment.failure" &&
      value.event !== "payment_request.expiry") {
    return { event: "ignored" };
  }
  if (!isRecord(value.data)) {
    throw new XenditPaymentError("Invalid Xendit webhook data.", 400);
  }

  const referenceId = requiredString(value.data.reference_id, "reference_id");
  const paymentRequestId = requiredString(
    value.data.payment_request_id,
    "payment_request_id"
  );

  if (value.event !== "payment.capture") {
    return {
      event: value.event,
      data: {
        reference_id: referenceId,
        payment_request_id: paymentRequestId,
      },
    };
  }

  if (
    value.data.type !== "PAY" ||
    value.data.country !== "PH" ||
    value.data.currency !== "PHP" ||
    value.data.channel_code !== "GCASH"
  ) {
    throw new XenditPaymentError(
      "Xendit capture must be a Philippines PHP GCash payment.",
      400
    );
  }
  if (value.data.status !== "SUCCEEDED") {
    throw new XenditPaymentError(
      "Xendit capture is not marked successful.",
      400
    );
  }
  const requestAmount = Number(value.data.request_amount);
  if (!Number.isFinite(requestAmount) || requestAmount <= 0) {
    throw new XenditPaymentError("Xendit capture amount is invalid.", 400);
  }
  if (!Array.isArray(value.data.captures) || value.data.captures.length === 0) {
    throw new XenditPaymentError("Xendit capture details are missing.", 400);
  }
  let captureAmount = 0;
  let captureId = "";
  for (const capture of value.data.captures) {
    if (!isRecord(capture)) {
      throw new XenditPaymentError("Xendit capture details are invalid.", 400);
    }
    const amount = Number(capture.capture_amount);
    if (!Number.isFinite(amount) || amount <= 0) {
      throw new XenditPaymentError("Xendit capture amount is invalid.", 400);
    }
    captureAmount += amount;
    captureId ||= requiredString(capture.capture_id, "capture_id");
  }
  if (Math.abs(captureAmount - requestAmount) > 0.01) {
    throw new XenditPaymentError(
      "Xendit captured amount does not match the payment request.",
      400
    );
  }

  return {
    event: "payment.capture",
    data: {
      payment_id: requiredString(value.data.payment_id, "payment_id"),
      payment_request_id: paymentRequestId,
      reference_id: referenceId,
      request_amount: requestAmount,
      capture_id: captureId,
      capture_amount: captureAmount,
    },
  };
}

export function isXenditTestMode() {
  const isProduction = process.env.NODE_ENV === "production";
  const testModeOverride = process.env.XENDIT_TEST_MODE;
  if (
    testModeOverride !== undefined &&
    testModeOverride !== "true" &&
    testModeOverride !== "false"
  ) {
    throw new XenditPaymentError(
      'XENDIT_TEST_MODE must be "true" or "false".',
      503
    );
  }
  return !isProduction || testModeOverride === "true";
}

export function getXenditConfig(requestUrl?: string) {
  const isTestMode = isXenditTestMode();
  const secretKey = isTestMode
    ? process.env.XENDIT_TEST_SECRET_KEY
    : process.env.XENDIT_SECRET_KEY;
  const callbackToken = process.env.XENDIT_WEBHOOK_TOKEN;
  const configuredAppUrl = process.env.APP_URL;

  if (!secretKey) {
    throw new XenditPaymentError(
      isTestMode
        ? "XENDIT_TEST_SECRET_KEY is not configured for this environment."
        : "XENDIT_SECRET_KEY is not configured.",
      503
    );
  }
  if (!callbackToken) {
    throw new XenditPaymentError(
      "Xendit webhook verification is not configured. Set XENDIT_WEBHOOK_TOKEN.",
      503
    );
  }
  if (!configuredAppUrl) {
    throw new XenditPaymentError(
      "Set APP_URL to the public HTTPS address of this app, or a local test address.",
      503
    );
  }

  let appUrl: URL;
  try {
    appUrl = new URL(configuredAppUrl);
  } catch {
    throw new XenditPaymentError(
      "APP_URL must be a valid HTTPS address or local test URL.",
      503
    );
  }
  const parts = appUrl.hostname.split(".").map(Number);
  const privateIpv4 = isIP(appUrl.hostname) === 4 &&
    (parts[0] === 10 ||
      parts[0] === 127 ||
      (parts[0] === 172 && parts[1] >= 16 && parts[1] <= 31) ||
      (parts[0] === 192 && parts[1] === 168));
  const allowInsecureLocal =
    isTestMode && (appUrl.hostname === "localhost" || privateIpv4);
  if (
    (allowInsecureLocal
      ? appUrl.protocol !== "http:" && appUrl.protocol !== "https:"
      : appUrl.protocol !== "https:") ||
    appUrl.pathname !== "/" ||
    appUrl.search ||
    appUrl.hash
  ) {
    throw new XenditPaymentError(
      "APP_URL must be an HTTPS origin or a local test origin without a path.",
      503
    );
  }

  if (allowInsecureLocal && appUrl.protocol === "http:" && requestUrl) {
    let requestOrigin: URL;
    try {
      requestOrigin = new URL(requestUrl);
    } catch {
      throw new XenditPaymentError("Invalid local return address.", 400);
    }
    const localAddresses = Object.values(networkInterfaces())
      .flatMap((entries) => entries ?? [])
      .filter((entry) => entry.family === "IPv4")
      .map((entry) => entry.address);
    if (
      !["http:", "https:"].includes(requestOrigin.protocol) ||
      requestOrigin.port !== appUrl.port ||
      requestOrigin.username ||
      requestOrigin.password ||
      !isPrivateAddress(requestOrigin.hostname) ||
      !["localhost", "127.0.0.1", ...localAddresses].includes(requestOrigin.hostname)
    ) {
      throw new XenditPaymentError(
        "Open the café system using this computer's current Wi-Fi address and try again.",
        400
      );
    }
    appUrl = requestOrigin;
  }

  return {
    secretKey,
    callbackToken,
    appUrl: appUrl.origin,
    mode: isTestMode ? "test" as const : "live" as const,
  };
}

export async function prepareXenditPayment(
  orderId: number,
  kind: XenditPaymentKind
): Promise<{
  reference_id: string;
  amount: number;
  payment_kind: XenditPaymentKind;
  order_id: number;
  checkout_url: string | null;
  checkout_mobile_url: string | null;
  checkout_qr_string: string | null;
  payment_request_id: string | null;
  status: string;
  expires_at_ms?: string | number;
}> {
  await ensureXenditPaymentTable();
  const db = getDb();
  return db.transaction(async () => {
    const order = await db
      .prepare(
        `SELECT id, status, payment_method, payment_status, total,
                payment_amount, payment_reference, payment_proof_url, table_number
         FROM orders
         WHERE id = $1
         FOR UPDATE`
      )
      .get(orderId) as
      | {
          id: number;
          status: string;
          payment_method: string;
          payment_status: string;
          total: number;
          payment_amount: number | null;
          payment_reference: string | null;
          payment_proof_url: string | null;
          table_number: number;
        }
      | undefined;

    if (!order) throw new XenditPaymentError("Order not found.", 404);
    if (kind === "order" && order.payment_method !== "gcash") {
      throw new XenditPaymentError("This order is not set to pay by GCash.", 400);
    }

    let amount = 0;
    if (kind === "order") {
      if (order.payment_status === "rejected") {
        throw new XenditPaymentError(
          "This payment needs staff review. If you already paid, show staff your original GCash receipt.",
          409
        );
      }
      if (
        order.payment_status !== "pending" ||
        !["pending", "payment_pending"].includes(order.status)
      ) {
        throw new XenditPaymentError(
          "This order is no longer waiting for GCash payment.",
          409
        );
      }
      if (order.payment_proof_url) {
        throw new XenditPaymentError(
          "A receipt for this order is already waiting for staff review.",
          409
        );
      }
      amount = Number(order.total);
    } else {
      if (
        order.payment_status !== "verified" ||
        order.status === "cancelled"
      ) {
        throw new XenditPaymentError(
          "An additional balance can only be paid on an active, paid order.",
          409
        );
      }
      const pendingBalance = await db
        .prepare(
          `SELECT 1 FROM order_balance_payments
           WHERE order_id = $1 AND status = 'pending'
           LIMIT 1`
        )
        .get(orderId);
      if (pendingBalance) {
        throw new XenditPaymentError(
          "An additional payment is already waiting for staff review.",
          409
        );
      }
      const paid = await db
        .prepare(
          `SELECT COALESCE(SUM(amount), 0) AS additional_paid
           FROM order_balance_payments
           WHERE order_id = $1 AND status = 'verified'`
        )
        .get(orderId) as { additional_paid: number };
      const initialPaid =
        order.payment_amount == null
          ? ["counter", "cash"].includes(order.payment_method)
            ? Number(order.total)
            : 0
          : Number(order.payment_amount);
      amount = Math.max(
        0,
        Math.round(
          (Number(order.total) -
            initialPaid -
            Number(paid.additional_paid || 0)) *
            100
        ) / 100
      );
      if (amount <= 0) {
        throw new XenditPaymentError(
          "This order has no outstanding balance.",
          409
        );
      }
    }

    const active = await db
      .prepare(
        `SELECT reference_id, amount, payment_kind, order_id, checkout_url,
                checkout_mobile_url, checkout_qr_string, payment_request_id, status,
                EXTRACT(EPOCH FROM (created_at + ${CHECKOUT_WINDOW})) * 1000 AS expires_at_ms
         FROM xendit_payment_requests
         WHERE order_id = $1 AND payment_kind = $2
           AND status IN ('creating', 'pending', 'mismatched', 'succeeded', 'succeeded_unapplied')
         ORDER BY created_at DESC
         LIMIT 1
         FOR UPDATE`
      )
      .get(orderId, kind) as
      | {
          reference_id: string;
          amount: number;
          payment_kind: XenditPaymentKind;
          order_id: number;
          checkout_url: string | null;
          checkout_mobile_url: string | null;
          checkout_qr_string: string | null;
          payment_request_id: string | null;
          status: string;
          expires_at_ms: string | number;
        }
      | undefined;
    if (active) {
      if (active.status === "pending" && active.checkout_url) return active;
      if (active.status !== "creating" && active.status !== "pending") {
        throw new XenditPaymentError("Ask staff to check this payment before paying again.", 409);
      }
      throw new XenditPaymentError(
        "Your GCash checkout is already being prepared. Please wait a moment and retry.",
        409
      );
    }

    const referenceId = `mlx_${kind}_${orderId}_${randomUUID().replaceAll("-", "")}`;
    await db
      .prepare(
        `INSERT INTO xendit_payment_requests
           (reference_id, order_id, payment_kind, amount, currency, status)
         VALUES ($1, $2, $3, $4, 'PHP', 'creating')`
      )
      .run(referenceId, orderId, kind, amount);

    if (kind === "order") {
      await db
        .prepare(
          `UPDATE orders
           SET payment_reference = $1,
               payment_proof_url = NULL,
               updated_at = to_char(timezone('Asia/Manila', CURRENT_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS')
           WHERE id = $2`
        )
        .run(referenceId, orderId);
    }

    return {
      reference_id: referenceId,
      amount,
      payment_kind: kind,
      order_id: orderId,
      checkout_url: null,
      checkout_mobile_url: null,
      checkout_qr_string: null,
      payment_request_id: null,
      status: "creating",
    };
  });
}

export async function switchExpiredXenditOrderToCounter(orderId: number) {
  await ensureXenditPaymentTable();
  const db = getDb();
  await db.transaction(async () => {
    const order = (await db.prepare(
      `SELECT status, payment_method, payment_status, payment_reference, payment_proof_url
       FROM orders WHERE id = $1 FOR UPDATE`
    ).get(orderId)) as {
      status: string;
      payment_method: string;
      payment_status: string;
      payment_reference: string | null;
      payment_proof_url: string | null;
    } | undefined;
    if (order?.payment_method === "counter" && order.status === "pending" && order.payment_status === "pending") return;
    if (
      order?.payment_method !== "gcash" ||
      order.payment_status !== "pending" ||
      !["pending", "payment_pending"].includes(order.status) ||
      order.payment_proof_url ||
      !(await db.prepare(
        `SELECT 1 FROM xendit_payment_requests
         WHERE order_id = $1 AND reference_id = $2 AND payment_kind = 'order'
           AND status = 'expired' AND payment_request_id IS NOT NULL
           AND NOT EXISTS (
             SELECT 1 FROM xendit_payment_requests other
             WHERE other.order_id = $1 AND other.payment_kind = 'order'
               AND other.status NOT IN ('failed', 'expired')
           )`
      ).get(orderId, order.payment_reference))
    ) {
      throw new XenditPaymentError("Cash is available only after Xendit confirms the checkout expired unpaid.", 409);
    }

    await db.prepare(
      `UPDATE orders SET payment_method = 'counter', status = 'pending',
         payment_reference = NULL, payment_amount = NULL,
         updated_at = to_char(timezone('Asia/Manila', CURRENT_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS')
       WHERE id = $1`
    ).run(orderId);
  });
}

export async function saveXenditPaymentRequest(
  referenceId: string,
  paymentRequestId: string,
  checkoutUrl: string,
  mobileUrl: string | null,
  qrString: string | null
) {
  await ensureXenditPaymentTable();
  const result = await getDb()
    .prepare(
      `UPDATE xendit_payment_requests
       SET payment_request_id = $1, checkout_url = $2,
           checkout_mobile_url = $3, checkout_qr_string = $4,
           status = 'pending', updated_at = CURRENT_TIMESTAMP
       WHERE reference_id = $5 AND status = 'creating'`
    )
    .run(paymentRequestId, checkoutUrl, mobileUrl, qrString, referenceId);
  if (result.changes !== 1) {
    throw new XenditPaymentError(
      "This GCash checkout could not be saved. Please try again.",
      409
    );
  }
}

export async function getXenditPaymentRequest(
  orderId: number,
  kind: XenditPaymentKind
) {
  await ensureXenditPaymentTable();
  return getDb()
    .prepare(
      `SELECT p.reference_id, p.payment_request_id, p.order_id, p.payment_kind, p.amount,
              p.checkout_url, p.checkout_mobile_url, p.checkout_qr_string, p.status,
              o.payment_status AS order_payment_status,
              EXTRACT(EPOCH FROM (p.created_at + ${CHECKOUT_WINDOW})) * 1000 AS expires_at_ms
       FROM xendit_payment_requests p
       LEFT JOIN orders o ON o.id = p.order_id
       WHERE p.order_id = $1 AND p.payment_kind = $2
       ORDER BY p.created_at DESC
       LIMIT 1`
    )
    .get(orderId, kind) as Promise<
    | {
        reference_id: string;
        payment_request_id: string | null;
        order_id: number;
        payment_kind: XenditPaymentKind;
        amount: number;
        checkout_url: string | null;
        checkout_mobile_url: string | null;
        checkout_qr_string: string | null;
        status: string;
        order_payment_status: string | null;
        expires_at_ms: string | number;
      }
    | undefined
  >;
}

async function updateXenditPaymentStatus(
  referenceId: string,
  status: "failed" | "expired" | "mismatched"
) {
  const db = getDb();
  return db.transaction(async () => {
    const attempt = await db
      .prepare(
        `SELECT status FROM xendit_payment_requests
         WHERE reference_id = $1 FOR UPDATE`
      )
      .get(referenceId) as { status: string } | undefined;
    if (!attempt) return "missing";
    if (attempt.status !== "pending" && attempt.status !== "creating") {
      return attempt.status;
    }
    await db
      .prepare(
        `UPDATE xendit_payment_requests
         SET status = $1, updated_at = CURRENT_TIMESTAMP
         WHERE reference_id = $2`
      )
      .run(status, referenceId);
    return status;
  });
}

export async function syncXenditPaymentStatus(
  orderId: number,
  kind: XenditPaymentKind,
  secretKey: string,
  expireAtDeadline = false
) {
  const attempt = await getXenditPaymentRequest(orderId, kind);
  if (!attempt) return { status: "not_found" as const };
  if (attempt.status !== "pending" || !attempt.payment_request_id) {
    return { status: attempt.status };
  }

  const paymentUrl = `https://api.xendit.co/v3/payment_requests/${encodeURIComponent(attempt.payment_request_id)}`;
  const readProviderStatus = async (cancel: boolean) => {
    const response = await fetch(cancel ? `${paymentUrl}/cancel` : paymentUrl, {
      method: cancel ? "POST" : "GET",
      headers: {
        Authorization: `Basic ${Buffer.from(`${secretKey}:`).toString("base64")}`,
        "api-version": "2024-11-11",
      },
      signal: AbortSignal.timeout(15_000),
    });
    if (!response.ok) {
      throw new XenditPaymentError(
        "Xendit has not confirmed the payment status. Please keep this page open.",
        502
      );
    }
    const payload: unknown = await response.json();
    if (
      !isRecord(payload) ||
      payload.payment_request_id !== attempt.payment_request_id ||
      payload.reference_id !== attempt.reference_id ||
      payload.type !== "PAY" ||
      payload.country !== "PH" ||
      payload.currency !== "PHP" ||
      payload.channel_code !== "GCASH"
    ) {
      throw new XenditPaymentError("Xendit returned payment details that do not match this checkout.", 502);
    }
    return payload;
  };
  let payload = await readProviderStatus(false);
  let amount = Number(payload.request_amount);
  if (
    expireAtDeadline && kind === "order" && payload.status === "REQUIRES_ACTION" &&
    Date.now() >= Number(attempt.expires_at_ms) &&
    Number.isFinite(amount) && Math.abs(amount - Number(attempt.amount)) <= 0.01
  ) {
    payload = await readProviderStatus(true);
    amount = Number(payload.request_amount);
  }
  if (!Number.isFinite(amount) || Math.abs(amount - Number(attempt.amount)) > 0.01) {
    return {
      status: await updateXenditPaymentStatus(attempt.reference_id, "mismatched"),
    };
  }

  if (payload.status === "SUCCEEDED") {
    const latestPaymentId =
      typeof payload.latest_payment_id === "string"
        ? payload.latest_payment_id
        : null;
    const result = await applyXenditCapture({
      payment_id: latestPaymentId,
      capture_id: null,
      payment_request_id: attempt.payment_request_id,
      reference_id: attempt.reference_id,
      request_amount: amount,
      capture_amount: amount,
    });
    return {
      status:
        result.action === "applied" || result.action === "duplicate"
          ? "succeeded"
          : "succeeded_unapplied",
    };
  }

  if (payload.status === "FAILED") {
    return {
      status: await updateXenditPaymentStatus(attempt.reference_id, "failed"),
    };
  }
  if (payload.status === "EXPIRED" || payload.status === "CANCELED") {
    return {
      status: await updateXenditPaymentStatus(attempt.reference_id, "expired"),
    };
  }
  if (
    ["ACCEPTING_PAYMENTS", "REQUIRES_ACTION", "AUTHORIZED", "PENDING"].includes(
      String(payload.status)
    )
  ) {
    return { status: "pending" as const };
  }

  throw new XenditPaymentError(
    "Xendit returned an unsupported payment status.",
    502
  );
}

export async function failXenditPaymentRequest(referenceId: string) {
  await ensureXenditPaymentTable();
  await getDb().transaction(async (db) => {
    await db
      .prepare(
        `UPDATE xendit_payment_requests
         SET status = 'failed', updated_at = CURRENT_TIMESTAMP
         WHERE reference_id = $1 AND status = 'creating'`
      )
      .run(referenceId);
    await db
      .prepare(
        `UPDATE orders
         SET payment_reference = NULL,
             updated_at = to_char(timezone('Asia/Manila', CURRENT_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS')
         WHERE payment_reference = $1 AND payment_status <> 'verified'`
      )
      .run(referenceId);
  });
}

export async function createXenditGcashRequest(input: {
  secretKey: string;
  appUrl: string;
  orderId: number;
  orderNumber: number;
  tableNumber: number;
  kind: XenditPaymentKind;
  referenceId: string;
  amount: number;
}): Promise<{
  paymentRequestId: string;
  checkoutUrl: string;
  mobileUrl: string | null;
  qrString: string | null;
}> {
  const paymentUrl = new URL("/customer/payment", input.appUrl);
  paymentUrl.searchParams.set("id", String(input.orderId));
  paymentUrl.searchParams.set("table", String(input.tableNumber));
  const failureUrl = new URL("/customer/payment", input.appUrl);
  failureUrl.searchParams.set("id", String(input.orderId));
  failureUrl.searchParams.set("table", String(input.tableNumber));
  if (input.kind === "balance") {
    paymentUrl.searchParams.set("balance", "1");
    failureUrl.searchParams.set("balance", "1");
  }

  const response = await fetch("https://api.xendit.co/v3/payment_requests", {
    method: "POST",
    headers: {
      Authorization: `Basic ${Buffer.from(`${input.secretKey}:`).toString("base64")}`,
      "Content-Type": "application/json",
      "api-version": "2024-11-11",
    },
    body: JSON.stringify({
      reference_id: input.referenceId,
      type: "PAY",
      country: "PH",
      currency: "PHP",
      request_amount: input.amount,
      capture_method: "AUTOMATIC",
      channel_code: "GCASH",
      channel_properties: {
        failure_return_url: failureUrl.toString(),
        success_return_url: paymentUrl.toString(),
      },
      description: `Merrylane Cafe order #${input.orderNumber}${
        input.kind === "balance" ? " additional balance" : ""
      }`,
      metadata: {
        order_id: String(input.orderId),
        payment_kind: input.kind,
      },
    }),
    signal: AbortSignal.timeout(20_000),
  });
  if (!response.ok) {
    console.error("Xendit payment request failed with status", response.status);
    throw new XenditPaymentError(
      "Xendit could not start this payment. Please try again.",
      502
    );
  }

  const payload: unknown = await response.json();
  if (!isRecord(payload) || !Array.isArray(payload.actions)) {
    throw new XenditPaymentError("Xendit returned an invalid checkout response.", 502);
  }
  const actions = payload.actions.filter(isRecord);
  const webAction = actions.find(
    (action) =>
      action.type === "REDIRECT_CUSTOMER" &&
      action.descriptor === "WEB_URL" &&
      typeof action.value === "string"
  );
  const mobileAction = actions.find(
    (action) =>
      action.type === "REDIRECT_CUSTOMER" &&
      ["DEEPLINK_URL", "MOBILE_URL"].includes(String(action.descriptor)) &&
      typeof action.value === "string"
  );
  const qrAction = actions.find(
    (action) =>
      action.type === "PRESENT_TO_CUSTOMER" &&
      action.descriptor === "QR_STRING" &&
      typeof action.value === "string"
  );
  const paymentRequestId = payload.payment_request_id;
  const actionValue = webAction?.value;
  if (typeof paymentRequestId !== "string" || typeof actionValue !== "string") {
    throw new XenditPaymentError(
      "Xendit did not return a GCash checkout link.",
      502
    );
  }
  let checkoutUrl: URL;
  try {
    checkoutUrl = new URL(actionValue);
  } catch {
    throw new XenditPaymentError("Xendit returned an invalid checkout link.", 502);
  }
  if (checkoutUrl.protocol !== "https:") {
    throw new XenditPaymentError("Xendit returned an insecure checkout link.", 502);
  }

  let mobileUrl: string | null = null;
  if (typeof mobileAction?.value === "string") {
    let parsedMobileUrl: URL;
    try {
      parsedMobileUrl = new URL(mobileAction.value);
    } catch {
      throw new XenditPaymentError("Xendit returned an invalid GCash app link.", 502);
    }
    if (!["https:", "gcash:"].includes(parsedMobileUrl.protocol)) {
      throw new XenditPaymentError("Xendit returned an unsupported GCash app link.", 502);
    }
    mobileUrl = parsedMobileUrl.toString();
  }

  const qrString = typeof qrAction?.value === "string" ? qrAction.value : null;
  if (qrString && Buffer.byteLength(qrString, "utf8") > 8192) {
    throw new XenditPaymentError(
      "Xendit returned a QR payment string that is too large.",
      502
    );
  }
  return {
    paymentRequestId,
    checkoutUrl: checkoutUrl.toString(),
    mobileUrl,
    qrString,
  };
}

type VerifiedXenditCapture = {
  payment_id: string | null;
  capture_id: string | null;
  payment_request_id: string;
  reference_id: string;
  request_amount: number;
  capture_amount: number;
};

async function applyXenditCapture(data: VerifiedXenditCapture) {
  await ensureXenditPaymentTable();
  const db = getDb();
  return db.transaction(async () => {
    const attempt = await db
      .prepare(
        `SELECT reference_id, payment_request_id, order_id, payment_kind,
                amount, status
         FROM xendit_payment_requests
         WHERE reference_id = $1
         FOR UPDATE`
      )
      .get(data.reference_id) as
      | {
          reference_id: string;
          payment_request_id: string | null;
          order_id: number;
          payment_kind: XenditPaymentKind;
          amount: number;
          status: string;
        }
      | undefined;
    if (!attempt) return { action: "unmatched" as const };
    if (!attempt.payment_request_id) {
      return { action: "retry" as const };
    }
    if (attempt.payment_request_id !== data.payment_request_id) {
      return { action: "unmatched" as const };
    }
    if (["succeeded", "succeeded_unapplied"].includes(attempt.status)) {
      await db
        .prepare(
          `UPDATE xendit_payment_requests
           SET payment_id = COALESCE($1, payment_id),
               capture_id = COALESCE($2, capture_id),
               updated_at = CURRENT_TIMESTAMP
           WHERE reference_id = $3`
        )
        .run(data.payment_id, data.capture_id, data.reference_id);
      if (attempt.status === "succeeded" && data.payment_id) {
        await db
          .prepare(
            `UPDATE orders
             SET payment_reference = $1
             WHERE id = $2 AND payment_reference = $3`
          )
          .run(data.payment_id, attempt.order_id, attempt.payment_request_id);
        await db
          .prepare(
            `UPDATE order_balance_payments
             SET payment_reference = $1
             WHERE order_id = $2 AND payment_reference = $3
               AND payment_method = 'gcash' AND status = 'verified'`
          )
          .run(data.payment_id, attempt.order_id, attempt.payment_request_id);
      }
      return { action: "duplicate" as const };
    }

    const amountMatches =
      Math.abs(Number(attempt.amount) - data.request_amount) <= 0.01 &&
      Math.abs(Number(attempt.amount) - data.capture_amount) <= 0.01;
    if (!amountMatches) {
      await db
        .prepare(
            `UPDATE xendit_payment_requests
             SET status = 'mismatched',
                 payment_id = COALESCE($1, payment_id),
                 capture_id = COALESCE($2, capture_id),
                 updated_at = CURRENT_TIMESTAMP
             WHERE reference_id = $3`
        )
        .run(
            data.payment_id,
            data.capture_id,
            data.reference_id
        );
      return {
        action: "unapplied" as const,
        reason: "amount_mismatch" as const,
      };
    }

    const order = await db
      .prepare(
        `SELECT id, status, payment_method, payment_status, total,
                payment_amount, payment_reference, payment_proof_url
         FROM orders
         WHERE id = $1
         FOR UPDATE`
      )
      .get(attempt.order_id) as
      | {
          id: number;
          status: string;
          payment_method: string;
          payment_status: string;
          total: number;
          payment_amount: number | null;
          payment_reference: string | null;
          payment_proof_url: string | null;
        }
      | undefined;
    let applied = false;
    if (order?.payment_method === "gcash" && attempt.payment_kind === "order") {
      const matchesPendingOrder =
        order.payment_status !== "verified" &&
        ["pending", "payment_pending"].includes(order.status) &&
        order.payment_reference === attempt.reference_id &&
        !order.payment_proof_url &&
        Math.abs(Number(order.total) - Number(attempt.amount)) <= 0.01;
      if (matchesPendingOrder) {
        const queue = await db
          .prepare(
            `SELECT COALESCE(MAX(queue_number), 0) + 1 AS next_queue_number
             FROM orders
             WHERE created_at::timestamp::date =
               timezone('Asia/Manila', CURRENT_TIMESTAMP)::date`
          )
          .get() as { next_queue_number: number };
        await db
          .prepare(
            `UPDATE orders
             SET status = 'confirmed', payment_status = 'verified',
                 payment_amount = $1, payment_reference = $2,
                 queue_number = COALESCE(queue_number, $3),
                 confirmed_at = COALESCE(
                   confirmed_at,
                   to_char(timezone('Asia/Manila', CURRENT_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS')
                 ),
                 updated_at = to_char(timezone('Asia/Manila', CURRENT_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS')
             WHERE id = $4`
          )
          .run(
            Number(attempt.amount),
            data.payment_id || data.payment_request_id,
            Number(queue.next_queue_number),
            order.id
          );
        applied = true;
      }
    } else if (
      order &&
      attempt.payment_kind === "balance" &&
      order.payment_status === "verified" &&
      order.status !== "cancelled"
    ) {
      const balanceState = await db
        .prepare(
          `SELECT
             COALESCE(SUM(amount), 0) AS additional_paid,
             COUNT(*) FILTER (WHERE status = 'pending') AS pending_count
           FROM order_balance_payments
           WHERE order_id = $1`
        )
        .get(order.id) as { additional_paid: number; pending_count: number };
      const initialPaid =
        order.payment_amount == null
          ? order.payment_method === "counter"
            ? Number(order.total)
            : 0
          : Number(order.payment_amount);
      const balanceDue = Math.max(
        0,
        Math.round(
          (Number(order.total) -
            initialPaid -
            Number(balanceState.additional_paid || 0)) *
            100
        ) / 100
      );
      if (
        Number(balanceState.pending_count) === 0 &&
        Math.abs(balanceDue - Number(attempt.amount)) <= 0.01
      ) {
        const verifiedAt = `to_char(timezone('Asia/Manila', CURRENT_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS')`;
        await db
          .prepare(
            `INSERT INTO order_balance_payments
               (order_id, amount, payment_method, status, payment_reference,
                payment_proof_url, received_by, verified_at)
             VALUES ($1, $2, 'gcash', 'verified', $3, NULL, NULL, ${verifiedAt})`
          )
          .run(
            order.id,
            Number(attempt.amount),
            data.payment_id || data.payment_request_id
          );
        applied = true;
      }
    }

    await db
      .prepare(
        `UPDATE xendit_payment_requests
         SET status = $1,
             payment_id = COALESCE($2, payment_id),
             capture_id = COALESCE($3, capture_id),
             updated_at = CURRENT_TIMESTAMP
         WHERE reference_id = $4`
      )
      .run(
        applied ? "succeeded" : "succeeded_unapplied",
        data.payment_id,
        data.capture_id,
        data.reference_id
      );

    return applied
      ? { action: "applied" as const }
      : { action: "unapplied" as const, reason: "order_not_payable" as const };
  });
}

export async function handleXenditWebhook(value: unknown) {
  const event = parseXenditWebhook(value);
  if (event.event === "ignored") return { action: "ignored" as const };

  await ensureXenditPaymentTable();
  const db = getDb();
  if (event.event !== "payment.capture") {
    return db.transaction(async () => {
      const attempt = await db
        .prepare(
          `SELECT status, payment_request_id
           FROM xendit_payment_requests
           WHERE reference_id = $1
           FOR UPDATE`
        )
        .get(event.data.reference_id) as
        | { status: string; payment_request_id: string | null }
        | undefined;
      if (
        !attempt ||
        attempt.payment_request_id !== event.data.payment_request_id
      ) {
        return { action: "unmatched" as const };
      }
      if (["succeeded", "succeeded_unapplied", "expired", "mismatched"].includes(attempt.status)) {
        return { action: "duplicate" as const };
      }
      await db
        .prepare(
          `UPDATE xendit_payment_requests
           SET status = $1, updated_at = CURRENT_TIMESTAMP
           WHERE reference_id = $2`
        )
        .run(
          event.event === "payment.failure" ? "failed" : "expired",
          event.data.reference_id
        );
      return { action: "updated" as const };
    });
  }

  return applyXenditCapture({
    payment_id: event.data.payment_id,
    capture_id: event.data.capture_id,
    payment_request_id: event.data.payment_request_id,
    reference_id: event.data.reference_id,
    request_amount: event.data.request_amount,
    capture_amount: event.data.capture_amount,
  });
}
